"""Question bank foundation: seeded batches, coverage and educational review (T047, ADR-034).

A batch is a fixed plan of `target` cells for one subject (objective, evidencia, difficulty), built by
`allocate(all objectives, target, "mixed")`. A cell is filled only by an eligible question for that exact
cell; nothing is borrowed from another cell. A run, under a per-subject advisory lock:

1. adopts eligible accepted questions (existing bank items, or seeder output a crashed run did not link)
   into unfilled cells: exact cell, current eligibility (ADR-014), D01 against the batch, never quarantined,
   never linked to another batch;
2. generates only the remaining gaps with the unchanged pipeline (`generate_set`, one cell at a time), within
   `max_calls` and the shared daily budget, linking each accepted question as soon as it is stored.

Three separate states: inventory (active linked questions / target), coverage (filled / planned cells, with
gaps) and educational readiness (`review_status`, from a reproducible 10-question review sample). Questions
generated by the seeder are held from practices until the batch review passes (`QuestionBank.eligible`).
Output is counts and identifiers only; question text is written only to the tutor's review file.
"""

from __future__ import annotations

import random
import uuid
import zlib
from collections import Counter
from collections.abc import Callable
from dataclasses import replace
from typing import Any

import psycopg
from psycopg.rows import dict_row
from psycopg.types.json import Jsonb

from app.allocation import allocate
from app.generation.practice_set import SetLimits, generate_set
from app.generation.validation import duplicate_reason
from app.practice.bank import QuestionBank
from curriculum.catalog import PracticeScope, select_objectives

LOCK_NAMESPACE = 4047  # first key of the two-key advisory lock (T047); the second is per baseline and subject
DEFAULT_TARGET = 100
SAMPLE_SIZE = 10
FAIL_QUARANTINES = 3  # this many quarantined sample questions fail the batch review
REASONS = ("wrong_key", "ambiguous", "off_curriculum", "level", "other")
BUDGET_STOPS = ("daily_budget", "set_call_limit")


class SeedError(RuntimeError):
    """A refused operation; nothing was changed by the refused step."""


class SeedBusy(SeedError):
    """Another seeding run holds the subject's lock."""


class LockLost(SeedError):
    """The run no longer owns its advisory lock; it stops before writing anything else."""


class SeedLock:
    """Session-level advisory lock on a dedicated connection, held for the whole run.

    `pg_try_advisory_lock` never waits: a competing run fails at once. PostgreSQL releases the lock when the
    connection ends, so a crashed run never leaves the subject locked. `verify()` checks in `pg_locks` that this
    connection still owns it; every write of a run goes through this connection after that check.
    """

    def __init__(self, url: str, baseline: str, subject: str):
        self.url = url
        self.key = (LOCK_NAMESPACE, zlib.crc32(f"{baseline}:{subject}".encode()) & 0x7FFFFFFF)
        self.conn: psycopg.Connection | None = None

    def __enter__(self) -> SeedLock:
        conn = psycopg.connect(self.url, autocommit=True, row_factory=dict_row)
        if not conn.execute("SELECT pg_try_advisory_lock(%s, %s) AS ok", self.key).fetchone()["ok"]:
            conn.close()
            raise SeedBusy("SEED BUSY: another seeding run holds this subject")
        self.conn = conn
        return self

    def verify(self) -> psycopg.Connection:
        try:
            owned = self.conn is not None and not self.conn.closed and self.conn.execute(
                """SELECT EXISTS (SELECT 1 FROM pg_locks WHERE locktype = 'advisory' AND granted
                       AND pid = pg_backend_pid() AND classid::bigint = %s AND objid::bigint = %s
                       AND objsubid = 2) AS owned""", self.key).fetchone()["owned"]
        except psycopg.Error:
            owned = False
        if not owned:
            raise LockLost("LOCK LOST: the seeding lock is no longer held; the run stopped")
        return self.conn

    def __exit__(self, *exc: Any) -> None:
        if self.conn is not None and not self.conn.closed:
            try:
                self.conn.execute("SELECT pg_advisory_unlock(%s, %s)", self.key)
            finally:
                self.conn.close()


def _connect(url: str) -> psycopg.Connection:
    return psycopg.connect(url, autocommit=True, row_factory=dict_row)


def build_plan(catalog: psycopg.Connection, baseline: str, subject: str, target: int) -> list[dict[str, Any]]:
    """Fixed cell plan: every multiple-choice objective of the subject, deterministic (`allocate`)."""
    selection = select_objectives(catalog, baseline, PracticeScope.SUBJECT_SIMULATION, subject)
    plan = allocate(selection.objectives, target, "mixed")["allocation"]
    return [{"cell": s["slot"], "objective_code": row["workbook_code"], "evidence_id": s["evidence_id"],
             "evidence_ordinal": s["evidence_ordinal"], "difficulty": s["difficulty"]}
            for row in plan for s in row["slots"]]


def current_batch(url: str, baseline: str, subject: str) -> dict[str, Any] | None:
    with _connect(url) as conn:
        return conn.execute(
            "SELECT * FROM generation.bank_batch WHERE baseline_version = %s AND subject = %s "
            "AND status IN ('open', 'filled')", (baseline, subject)).fetchone()


def get_batch(url: str, batch_id: str) -> dict[str, Any]:
    with _connect(url) as conn:
        batch = conn.execute("SELECT * FROM generation.bank_batch WHERE batch_id = %s", (batch_id,)).fetchone()
    if batch is None:
        raise SeedError(f"unknown batch {batch_id}")
    return batch


def links(url: str, batch_id: str) -> list[dict[str, Any]]:
    with _connect(url) as conn:
        return conn.execute(
            """SELECT bi.*, q.item, q.practice_set_id FROM generation.bank_batch_item bi
               JOIN generation.question_attempt q USING (request_id)
               WHERE bi.batch_id = %s ORDER BY bi.cell, bi.linked_at""", (batch_id,)).fetchall()


def _active(rows: list[dict[str, Any]]) -> dict[int, dict[str, Any]]:
    return {r["cell"]: r for r in rows if r["active"]}


def _open_or_resume(lock: SeedLock, catalog: psycopg.Connection, baseline: str, subject: str,
                    target: int) -> dict[str, Any]:
    batch = current_batch(lock.url, baseline, subject)
    if batch is not None:
        if batch["target"] != target:
            raise SeedError(f"batch {batch['batch_id']} has target {batch['target']}, not {target}")
        return batch
    plan = build_plan(catalog, baseline, subject, target)
    batch_id = f"bb-{subject}-{uuid.uuid4().hex[:8]}"
    return lock.verify().execute(
        """INSERT INTO generation.bank_batch (batch_id, baseline_version, subject, target, plan, status, review_seed)
           VALUES (%s, %s, %s, %s, %s, 'open', %s) RETURNING *""",
        (batch_id, baseline, subject, target, Jsonb(plan), uuid.uuid4().hex)).fetchone()


def _link(lock: SeedLock, batch: dict[str, Any], cell: int, request_id: str, origin: str) -> None:
    lock.verify().execute(
        "INSERT INTO generation.bank_batch_item (batch_id, cell, request_id, origin) VALUES (%s, %s, %s, %s)",
        (batch["batch_id"], cell, request_id, origin))


def _linked_anywhere(url: str) -> set[str]:
    with _connect(url) as conn:
        return {r["request_id"] for r in conn.execute("SELECT request_id FROM generation.bank_batch_item")}


def _origin(batch: dict[str, Any], candidate: dict[str, Any]) -> str:
    seed_prefix = f"seed-{batch['batch_id']}-"
    return "generated" if (candidate.get("practice_set_id") or "").startswith(seed_prefix) else "adopted"


def _adopt(lock: SeedLock, bank: QuestionBank, catalog: psycopg.Connection, batch: dict[str, Any]) -> int:
    """Fill unfilled cells from eligible accepted questions; returns how many were linked."""
    active = _active(links(lock.url, batch["batch_id"]))
    chosen = [r["item"] for r in active.values()]
    taken = _linked_anywhere(lock.url)
    adopted = 0
    for cell in batch["plan"]:
        if cell["cell"] in active:
            continue
        candidates = bank.eligible(catalog, batch["baseline_version"], batch["subject"], cell["objective_code"],
                                   cell["evidence_ordinal"], cell["evidence_id"], cell["difficulty"],
                                   include_held=True)
        for c in candidates:
            origin = _origin(batch, c)
            other_seeder = origin == "adopted" and (c.get("practice_set_id") or "").startswith("seed-")
            if (c["request_id"] in taken or other_seeder  # another batch's held output is never adopted here
                    or any(c["item"]["item_id"] == i["item_id"] for i in chosen)
                    or duplicate_reason(c["item"], chosen) is not None):
                continue
            _link(lock, batch, cell["cell"], c["request_id"], origin)
            chosen.append(c["item"])
            taken.add(c["request_id"])
            adopted += 1
            break
    return adopted


def _set_fill_status(lock: SeedLock, batch: dict[str, Any]) -> str:
    """`filled` when every planned cell has an active question, else `open` (never changes `short`)."""
    filled = len(_active(links(lock.url, batch["batch_id"]))) == len(batch["plan"])
    status = "filled" if filled else "open"
    lock.verify().execute(
        "UPDATE generation.bank_batch SET status = %s, updated_at = now() WHERE batch_id = %s AND status <> 'short'",
        (status, batch["batch_id"]))
    return status


def run(url: str, catalog: psycopg.Connection, baseline: str, subject: str, llm_factory: Callable[[], tuple],
        target: int = DEFAULT_TARGET, max_calls: int = 20, limits: SetLimits | None = None) -> dict[str, Any]:
    """One resumable seeding run (adopt, then generate gaps). Raises SeedBusy or LockLost; returns a report."""
    if max_calls < 0:
        raise SeedError("max_calls must be zero or positive")
    bank = QuestionBank(url)
    with SeedLock(url, baseline, subject) as lock:
        batch = _open_or_resume(lock, catalog, baseline, subject, target)
        adopted = _adopt(lock, bank, catalog, batch)
        generated, calls, stop = 0, 0, None
        gaps = [c for c in batch["plan"] if c["cell"] not in _active(links(url, batch["batch_id"]))]
        if gaps and max_calls > 0:
            generated, calls, stop = _generate(lock, catalog, batch, gaps, llm_factory, max_calls,
                                               limits or SetLimits.from_env())
        elif gaps:
            stop = "run_call_limit"
        status = _set_fill_status(lock, batch)
        lock.verify()
    out = report(url, catalog, batch["batch_id"])
    out["run"] = {"adopted": adopted, "generated": generated, "calls": calls, "stop_reason": stop,
                  "status": status}
    return out


def _generate(lock: SeedLock, catalog: psycopg.Connection, batch: dict[str, Any], gaps: list[dict[str, Any]],
              llm_factory: Callable[[], tuple], max_calls: int, base: SetLimits) -> tuple[int, int, str | None]:
    """Generate gap cells one at a time with the unchanged pipeline; link each accepted, non-duplicate item."""
    client, usage_store, generation_store = llm_factory()
    run_id = f"seed-{batch['batch_id']}-{uuid.uuid4().hex[:6]}"
    objective_of = {c["cell"]: c["objective_code"] for c in batch["plan"]}
    generated = calls = 0
    try:
        for cell in gaps:
            remaining = max_calls - calls
            if remaining <= 0:
                return generated, calls, "run_call_limit"
            lock.verify()
            active = _active(links(lock.url, batch["batch_id"]))
            chosen = [r["item"] for r in active.values()]
            # Prompt-side avoidance stays per objective (stems go into the prompt); D01 below covers the batch.
            same_objective = [r["item"] for c, r in active.items() if objective_of[c] == cell["objective_code"]]
            allocation = [{"workbook_code": cell["objective_code"], "questions": 1, "slots": [
                {"slot": cell["cell"], "evidence_id": cell["evidence_id"],
                 "evidence_ordinal": cell["evidence_ordinal"], "difficulty": cell["difficulty"]}]}]
            limits = replace(base, max_questions=1, max_calls_per_set=remaining, concurrency=1)
            result = generate_set(catalog, client, usage_store, generation_store, batch["baseline_version"],
                                  batch["subject"], allocation, limits, practice_set_id=run_id,
                                  seed_items=same_objective)
            calls += result.summary()["calls"]
            slot = result.slots[0]
            if slot.status == "accepted" and duplicate_reason(slot.item, chosen) is None \
                    and all(slot.item["item_id"] != i["item_id"] for i in chosen):
                _link(lock, batch, cell["cell"], slot.request_id, "generated")
                generated += 1
            if result.stop_reason in BUDGET_STOPS:  # the set call limit is this run's remaining max_calls
                return generated, calls, ("run_call_limit" if result.stop_reason == "set_call_limit"
                                          else result.stop_reason)
        return generated, calls, None
    finally:
        client.close()


# ---------------------------------------------------------------- reporting

def _rollup(cells: list[dict[str, Any]], key: Callable[[dict[str, Any]], Any]) -> list[dict[str, Any]]:
    planned, filled = Counter(), Counter()
    for c in cells:
        planned[key(c)] += 1
        filled[key(c)] += c["status"] == "filled"
    return [{"key": k, "planned": planned[k], "filled": filled[k], "gaps": planned[k] - filled[k]}
            for k in planned]


def report(url: str, catalog: psycopg.Connection, batch_id: str) -> dict[str, Any]:
    """Inventory, coverage (by cell, objective, evidencia, difficulty, and unplanned curriculum) and readiness."""
    batch = get_batch(url, batch_id)
    rows = links(url, batch_id)
    active = _active(rows)
    seen = QuestionBank(url).seen_questions()
    seed_prefix = f"seed-{batch_id}-"
    with _connect(url) as conn:
        failed = Counter(r["slot"] for r in conn.execute(
            "SELECT slot FROM generation.question_attempt WHERE practice_set_id LIKE %s AND status <> 'accepted'",
            (seed_prefix + "%",)))
    cells = []
    for c in batch["plan"]:
        link = active.get(c["cell"])
        cells.append({**{k: c[k] for k in ("cell", "objective_code", "evidence_id", "difficulty")},
                      "status": "filled" if link else "gap", "origin": link["origin"] if link else None,
                      "request_id": link["request_id"] if link else None,
                      "seen": bool(link and link["item"]["item_id"] in seen),
                      "failed_attempts": failed.get(c["cell"], 0)})
    objectives = select_objectives(catalog, batch["baseline_version"], PracticeScope.SUBJECT_SIMULATION,
                                   batch["subject"]).objectives
    planned_objectives = {c["objective_code"] for c in batch["plan"]}
    planned_evidences = {c["evidence_id"] for c in batch["plan"]}
    filled = sum(1 for c in cells if c["status"] == "filled")
    return {
        "batch_id": batch_id, "subject": batch["subject"], "baseline_version": batch["baseline_version"],
        "status": batch["status"],
        "inventory": {"validated": len(active), "target": batch["target"],
                      "adopted": sum(1 for r in active.values() if r["origin"] == "adopted"),
                      "generated": sum(1 for r in active.values() if r["origin"] == "generated"),
                      "held_from_practice": sum(1 for r in active.values() if r["origin"] == "generated")
                      if batch["review_status"] != "passed" else 0,
                      "seen_by_student": sum(1 for c in cells if c["seen"]),
                      "deactivated": sum(1 for r in rows if not r["active"])},
        "coverage": {
            "planned_cells": len(cells), "filled_cells": filled, "gap_cells": len(cells) - filled,
            "by_objective": _rollup(cells, lambda c: c["objective_code"]),
            "by_evidencia": _rollup(cells, lambda c: c["evidence_id"]),
            "by_difficulty": _rollup(cells, lambda c: c["difficulty"]),
            "unplanned_objectives": sorted(o["workbook_code"] for o in objectives
                                           if o["workbook_code"] not in planned_objectives),
            "unplanned_evidencias": sorted(e["id"] for o in objectives for e in o["evidences"]
                                           if e["id"] not in planned_evidences),
            "cells": cells},
        "readiness": review_state(url, batch_id),
    }


# ---------------------------------------------------------------- educational review

def _samples(url: str, batch_id: str) -> list[dict[str, Any]]:
    with _connect(url) as conn:
        return conn.execute(
            """SELECT s.*, (SELECT v.verdict FROM generation.bank_item_review v WHERE v.request_id = s.request_id
                            ORDER BY v.review_id DESC LIMIT 1) AS verdict
               FROM generation.bank_review_sample s WHERE s.batch_id = %s ORDER BY s.round, s.position""",
            (batch_id,)).fetchall()


def review_state(url: str, batch_id: str) -> dict[str, Any]:
    samples = _samples(url, batch_id)
    batch = get_batch(url, batch_id)
    return {"review_status": batch["review_status"], "rounds": max((s["round"] for s in samples), default=0),
            "sampled": len(samples), "approved": sum(1 for s in samples if s["verdict"] == "approved"),
            "quarantined": sum(1 for s in samples if s["verdict"] == "quarantined"),
            "unreviewed": sum(1 for s in samples if s["verdict"] is None)}


def draw_sample(cells: list[int], difficulty: dict[int, str], seed: str, size: int = SAMPLE_SIZE) -> list[int]:
    """Reproducible sample: shuffle each difficulty with a seeded generator, then take round-robin."""
    rng = random.Random(seed)
    groups = {}
    for level in ("easy", "medium", "hard"):
        group = sorted(c for c in cells if difficulty[c] == level)
        rng.shuffle(group)
        groups[level] = group
    picked: list[int] = []
    while len(picked) < min(size, len(cells)):
        for level in ("easy", "medium", "hard"):
            if groups[level] and len(picked) < size:
                picked.append(groups[level].pop(0))
    return picked


def review_sample(url: str, batch_id: str) -> list[dict[str, Any]]:
    """Open the next review round: round 1 samples the filled batch; later rounds hold the not yet reviewed
    replacements in every reopened cell (a quarantined question, sampled or not). Earlier rounds and their
    verdicts are never changed."""
    batch = get_batch(url, batch_id)
    if batch["status"] != "filled":
        raise SeedError("the batch must be filled before review sampling")
    if batch["review_status"] != "pending":
        raise SeedError(f"the batch review is already {batch['review_status']}")
    samples = _samples(url, batch_id)
    if any(s["verdict"] is None for s in samples):
        raise SeedError("the current review round still has unreviewed questions")
    rows = links(url, batch_id)
    active = _active(rows)
    if not samples:
        difficulty = {c["cell"]: c["difficulty"] for c in batch["plan"]}
        cells = draw_sample(sorted(active), difficulty, f"{batch_id}:{batch['review_seed']}")
        round_no = 1
    else:
        sampled = {s["request_id"] for s in samples}
        cells = [c for c in _reopened(rows) if active[c]["request_id"] not in sampled]
        if not cells:
            raise SeedError("no replacement questions are waiting for review")
        round_no = max(s["round"] for s in samples) + 1
    with _connect(url) as conn, conn.transaction():
        for position, cell in enumerate(cells, start=1):
            conn.execute(
                """INSERT INTO generation.bank_review_sample (batch_id, round, position, cell, request_id)
                   VALUES (%s, %s, %s, %s, %s)""", (batch_id, round_no, position, cell, active[cell]["request_id"]))
    return [s for s in _samples(url, batch_id) if s["round"] == round_no]


def _reopened(rows: list[dict[str, Any]]) -> list[int]:
    """Cells that ever lost a question to quarantine (their current question must be reviewed)."""
    return sorted({r["cell"] for r in rows if not r["active"]})


def review_export(url: str, catalog: psycopg.Connection, batch_id: str) -> dict[str, Any]:
    """The tutor's review file for the current round (question text, key, explanation, curriculum text)."""
    batch = get_batch(url, batch_id)
    samples = [s for s in _samples(url, batch_id) if s["verdict"] is None]
    items = {r["request_id"]: r["item"] for r in links(url, batch_id)}
    plan = {c["cell"]: c for c in batch["plan"]}
    objectives = {o["workbook_code"]: o for o in select_objectives(
        catalog, batch["baseline_version"], PracticeScope.SUBJECT_SIMULATION, batch["subject"]).objectives}
    questions = []
    for s in samples:
        item, cell = items[s["request_id"]], plan[s["cell"]]
        objective = objectives[cell["objective_code"]]
        evidence = next(e for e in objective["evidences"] if e["id"] == cell["evidence_id"])
        questions.append({
            "request_id": s["request_id"], "round": s["round"], "cell": s["cell"],
            "objective_code": cell["objective_code"], "objective_es": objective["text_es"],
            "evidencia_es": evidence.get("text_es", ""), "difficulty": cell["difficulty"],
            "stimulus": item.get("stimulus"), "stem": item["stem"], "options": item["options"],
            "answer_key": item["answer_key"], "explanation": item.get("explanation"),
            "verdict": "", "reason": ""})
    return {"batch_id": batch_id, "instructions": "verdict: approved | quarantined; reason (quarantined): "
            + " | ".join(REASONS), "questions": questions}


def _record_verdict(conn: psycopg.Connection, request_id: str, batch_id: str | None, verdict: str, reason: str,
                    reviewer: str) -> None:
    conn.execute(
        """INSERT INTO generation.bank_item_review (request_id, batch_id, verdict, reason, reviewer)
           VALUES (%s, %s, %s, %s, %s)""", (request_id, batch_id, verdict, reason, reviewer))
    if verdict == "quarantined":
        conn.execute(
            """UPDATE generation.bank_batch_item SET active = false, deactivated_at = now()
               WHERE request_id = %s AND active""", (request_id,))
        # The cell reopens; a passed review returns to pending so the replacement is reviewed before release.
        conn.execute(
            """UPDATE generation.bank_batch SET updated_at = now(),
                   status = CASE WHEN status = 'filled' THEN 'open' ELSE status END,
                   review_status = CASE WHEN review_status = 'passed' THEN 'pending' ELSE review_status END
               WHERE batch_id IN (SELECT batch_id FROM generation.bank_batch_item WHERE request_id = %s)""",
            (request_id,))


def _check(verdict: str, reason: str) -> tuple[str, str]:
    if verdict == "approved" and reason in ("", "approved"):
        return verdict, "approved"
    if verdict == "quarantined" and reason in REASONS:
        return verdict, reason
    raise SeedError(f"invalid decision {verdict!r}/{reason!r}")


def review_record(url: str, batch_id: str, decisions: list[dict[str, str]], reviewer: str = "tutor") -> dict:
    """Record the tutor's verdicts for the current round (all or nothing), then evaluate the gate:
    `failed` at FAIL_QUARANTINES quarantined sample questions; `passed` when every sampled cell ends with an
    approved active question in a filled batch; otherwise `pending`."""
    pending = {s["request_id"]: s for s in _samples(url, batch_id) if s["verdict"] is None}
    if get_batch(url, batch_id)["review_status"] != "pending":
        raise SeedError("the batch review is already decided")
    checked = []
    for d in decisions:
        if d.get("request_id") not in pending:
            raise SeedError(f"{d.get('request_id')} is not awaiting review in this batch")
        checked.append((d["request_id"], *_check(d.get("verdict", ""), d.get("reason", ""))))
    if len({c[0] for c in checked}) != len(checked):
        raise SeedError("a question appears twice in the decisions")
    with _connect(url) as conn, conn.transaction():
        for request_id, verdict, reason in checked:
            _record_verdict(conn, request_id, batch_id, verdict, reason, reviewer)
    return {**_evaluate_gate(url, batch_id), "recorded": len(checked)}


def _evaluate_gate(url: str, batch_id: str) -> dict[str, Any]:
    samples = _samples(url, batch_id)
    batch = get_batch(url, batch_id)
    rows = links(url, batch_id)
    active = _active(rows)
    latest = {s["request_id"]: s["verdict"] for s in samples}
    checked = {s["cell"] for s in samples} | set(_reopened(rows))
    status = "pending"
    if sum(1 for s in samples if s["verdict"] == "quarantined") >= FAIL_QUARANTINES:
        status = "failed"
    elif samples and batch["status"] == "filled" and all(
            c in active and latest.get(active[c]["request_id"]) == "approved" for c in checked):
        status = "passed"
    if status != "pending":
        with _connect(url) as conn:
            conn.execute("UPDATE generation.bank_batch SET review_status = %s, updated_at = now() "
                         "WHERE batch_id = %s", (status, batch_id))
    return review_state(url, batch_id)


def quarantine(url: str, request_id: str, reason: str, reviewer: str = "tutor") -> dict[str, Any]:
    """Quarantine any accepted question (append-only). A linked question's cell reopens as a gap."""
    _, reason = _check("quarantined", reason)
    with _connect(url) as conn, conn.transaction():
        found = conn.execute("SELECT 1 FROM generation.question_attempt WHERE request_id = %s AND status = 'accepted'",
                             (request_id,)).fetchone()
        if found is None:
            raise SeedError(f"{request_id} is not an accepted question")
        batch = conn.execute("SELECT batch_id FROM generation.bank_batch_item WHERE request_id = %s",
                             (request_id,)).fetchone()
        _record_verdict(conn, request_id, batch["batch_id"] if batch else None, "quarantined", reason, reviewer)
    return {"request_id": request_id, "quarantined": True, "batch_id": batch["batch_id"] if batch else None}
